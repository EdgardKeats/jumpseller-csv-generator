package cl.rivendel.csv.model.jumpseller;

public class CSVCustomField {

    private String customField;
    private String customFieldLabel;
    private String customFieldValue;
    private String customFieldType;

    public String getCustomField() {
        return customField;
    }

    public void setCustomField(String customField) {
        this.customField = customField;
    }

    public String getCustomFieldLabel() {
        return customFieldLabel;
    }

    public void setCustomFieldLabel(String customFieldLabel) {
        this.customFieldLabel = customFieldLabel;
    }

    public String getCustomFieldValue() {
        return customFieldValue;
    }

    public void setCustomFieldValue(String customFieldValue) {
        this.customFieldValue = customFieldValue;
    }

    public String getCustomFieldType() {
        return customFieldType;
    }

    public void setCustomFieldType(String customFieldType) {
        this.customFieldType = customFieldType;
    }
}
